function t(s) {
  if (lang !== 'en' || s == null) return s;
  const key = String(s);
  return Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : key;
}
function tf(zh, en) { return lang === 'en' ? en : zh; }
function setLang(next) {
  lang = next === 'en' ? 'en' : 'zh';
  try { localStorage.setItem('tikzStudioLang', lang); } catch {}
  applyI18n();
}
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = t(key);
    else el.textContent = t(key);
    const title = el.getAttribute('data-i18n-title');
    if (title) el.title = t(title);
  });
  const button = document.getElementById('lang');
  if (button) button.textContent = lang === 'en' ? '中文' : 'EN';
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
}
